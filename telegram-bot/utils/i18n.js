// Supported language codes
const SUPPORTED_LANGS = ['en', 'zh', 'es', 'ar', 'fr', 'ru'];

/**
 * Get translation string by key
 * @param {string} key - Translation key
 * @param {string} lang - Language code (default: 'en')
 * @returns {string} Translated string or key fallback
 */
function t(key, lang = DEFAULT_LANG) {
  const langCode = SUPPORTED_LANGS.includes(lang) ? lang : DEFAULT_LANG;
  return translations[langCode]?.[key] || translations[DEFAULT_LANG][key] || key;
}

/**
 * Get all supported languages info
 * @returns {Array<{code: string, name: string}>}
 */
function getSupportedLanguages() {
  return [
    { code: 'en', name: 'English', flag: '🇬🇧' },
    { code: 'zh', name: '中文', flag: '🇨🇳' },
    { code: 'es', name: 'Español', flag: '🇪🇸' },
    { code: 'ar', name: 'العربية', flag: '🇸🇦' },
    { code: 'fr', name: 'Français', flag: '🇫🇷' },
    { code: 'ru', name: 'Русский', flag: '🇷🇺' }
  ];
}

/**
 * Detect language from user info
 * @param {Object} user - Telegram user object
 * @returns {string} Language code
 */
function detectLanguage(user = {}) {
  if (!user.language_code) return DEFAULT_LANG;
  const code = user.language_code.split('-')[0];
  return SUPPORTED_LANGS.includes(code) ? code : DEFAULT_LANG;
}

